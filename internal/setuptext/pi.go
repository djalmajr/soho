package setuptext

import "strings"

const PiInboundMarker = "// soho: inbound peer check (managed by soho setup)"

// PiInboundExtension is TypeScript that Pi loads directly; its only annotations
// type the two untyped lets, so strict linters (noImplicitAnyLet) accept it.
func PiInboundExtension() string { return piInboundText }

func PiInboundManaged(content string) bool {
	line, _, _ := strings.Cut(content, "\n")
	return strings.TrimSuffix(line, "\r") == PiInboundMarker
}

func PiInboundResult(content *string) *string {
	if content != nil && !PiInboundManaged(*content) {
		return nil
	}
	text := PiInboundExtension()
	return &text
}

func PiInboundProtected(content string) bool {
	return content == PiInboundExtension()
}

const piInboundText = PiInboundMarker + `
// biome-ignore-all format: Generated by soho setup; preserve the managed file's formatting.
import { spawn } from "node:child_process";

const timeoutMS = 10000;

function runHook(args, payload) {
  return new Promise((resolve) => {
    let child: ReturnType<typeof spawn>;
    try {
      child = spawn("soho", args, {
        shell: false,
        stdio: ["pipe", "pipe", "ignore"],
      });
    } catch (error) {
      resolve({ error: error.code || "spawn failed" });
      return;
    }
    let output = "";
    let settled = false;
    let timedOut = false;
    const timer = setTimeout(() => {
      timedOut = true;
      child.kill("SIGKILL");
    }, timeoutMS);
    const finish = (result) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve(result);
    };
    child.on("error", (error) =>
      finish({ error: error.code || "spawn failed" }),
    );
    child.stdout.setEncoding("utf8");
    child.stdout.on("data", (chunk) => {
      output += chunk;
    });
    child.on("close", (code) => {
      if (timedOut) finish({ error: "timeout" });
      else if (code !== 0) finish({ error: ` + "`" + `exit ${code ?? "signal"}` + "`" + ` });
      else finish({ output });
    });
    child.stdin.on("error", () => {});
    child.stdin.end(JSON.stringify(payload));
  });
}

function checkPeer(text) {
  return runHook(["hook", "inbound", "--pi"], {
    hook_event_name: "UserPromptSubmit",
    prompt: text,
    cwd: process.cwd(),
  });
}

export default function (pi) {
  // The reminder and the doctor's warnings reach the model once per session
  // start: session_start arms the delivery for the startup and new reasons,
  // and the first before_agent_start after the arm runs both hooks (a
  // ten-second deadline each), disarms, and returns their text as a custom
  // message. A failed or timed-out hook notifies a warning and the session
  // goes on; the hooks never block, and the text always comes from the
  // soho binary, so nothing is delivered outside Herdr.
  let deliveryArmed = false;
  pi.on("input", async (event, ctx) => {
    // The prefilter accepts the current format's opening tag
    // [soho:peer:<id>] and the previous format's marker [soho:peer]
    // (accepted for one release); the exact check runs in the soho hook
    // inbound --pi command.
    if (typeof event.text !== "string" || !event.text.includes("[soho:peer")) {
      return { action: "continue" };
    }
    const result = await checkPeer(event.text);
    let decision: { decision?: unknown; reason?: unknown } | undefined;
    if (!result.error && result.output.trim() !== "") {
      try {
        decision = JSON.parse(result.output);
      } catch {}
      if (
        !decision ||
        typeof decision !== "object" ||
        Array.isArray(decision)
      ) {
        result.error = "unreadable output";
      }
    }
    if (result.error) {
      ctx.ui.notify(
        "soho: peer check did not run (" +
          result.error +
          "); the message was not checked",
        "warning",
      );
      return { action: "continue" };
    }
    if (
      decision &&
      decision.decision === "block" &&
      typeof decision.reason === "string"
    ) {
      ctx.ui.notify(decision.reason, "error");
      return { action: "handled" };
    }
    return { action: "continue" };
  });
  pi.on("session_start", (event) => {
    if (event.reason === "startup" || event.reason === "new") {
      deliveryArmed = true;
    }
  });
  pi.on("before_agent_start", async (event, ctx) => {
    if (!deliveryArmed) return;
    deliveryArmed = false;
    const text: string[] = [];
    for (const [name, args, payload] of [
      [
        "reminder",
        ["hook", "reminder", "--pi"],
        { hook_event_name: "UserPromptSubmit", prompt: "", cwd: process.cwd() },
      ],
      ["doctor", ["hook", "doctor", "--pi"], {}],
    ]) {
      const result = await runHook(args, payload);
      if (result.error) {
        ctx.ui.notify(
          "soho: session " + name + " did not run (" + result.error + ")",
          "warning",
        );
        continue;
      }
      if (result.output.trim() !== "") text.push(result.output.trim());
    }
    if (text.length === 0) return;
    return {
      message: {
        customType: "soho-reminder",
        content: text.join("\n"),
        display: true,
      },
    };
  });
}
`
