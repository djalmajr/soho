package setuptext

import (
	"strings"
	"testing"
)

func TestPiInboundGeneratedStyle(t *testing.T) {
	text := PiInboundExtension()
	const header = PiInboundMarker + "\n// biome-ignore-all format: Generated by soho setup; preserve the managed file's formatting.\n"
	if !strings.HasPrefix(text, header) {
		t.Fatal("generated extension must keep its first-line marker followed by the formatter suppression")
	}
	const exit = "else if (code !== 0) finish({ error: `exit ${code ?? \"signal\"}` });"
	if !strings.Contains(text, exit) || strings.Contains(text, `"exit " +`) {
		t.Fatal("generated extension must use a template literal for the exit error")
	}
	if !PiInboundManaged(text) || PiInboundResult(&text) == nil {
		t.Fatal("generated extension must remain recognized for refresh")
	}
	movedMarker := strings.TrimPrefix(text, PiInboundMarker+"\n") + PiInboundMarker + "\n"
	if PiInboundManaged(movedMarker) || PiInboundResult(&movedMarker) != nil {
		t.Fatal("a marker outside the first line must not authorize overwriting a foreign extension")
	}
}
